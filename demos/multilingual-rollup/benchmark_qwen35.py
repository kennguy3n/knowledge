#!/usr/bin/env python3
"""
Live A/B benchmark: Qwen3.5-0.8B and Qwen3.5-2B vs the recorded Bonsai-1.7B baseline.

Drives the multilingual matrix's synthesis prompts directly against one or two
llama-server instances (no Knowledge gateway needed) and scores the output with
the same deterministic scorers used by the synthesis-eval harness.

Usage:
    # Start llama-servers first:
    #   llama-server --model qwen3.5-0.8b-q4_k_m.gguf --port 8083 -c 4096
    #   llama-server --model qwen3.5-2b-q4_k_m.gguf   --port 8084 -c 4096
    #
    LLAMA_08B_URL=http://127.0.0.1:8083 \
    LLAMA_2B_URL=http://127.0.0.1:8084 \
    python3 demos/multilingual-rollup/benchmark_qwen35.py

Outputs:
    results/qwen35_benchmark.json  — machine-readable results
    results/qwen35_benchmark.md    — human-readable comparison table
"""


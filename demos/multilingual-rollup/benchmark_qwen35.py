LLAMA_2B = os.environ.get("LLAMA_2B_URL", "http://127.0.0.1:8084").rstrip("/")


def benchmark_model(base_url: str, dataset: dict, model_name: str) -> dict:
    """Drive the multilingual matrix against a single llama-server."""
    langs = dataset["multilingual_matrix"]["languages"]
    results = {}
    for lang, bodies in langs.items():
        t0 = time.time()
        try:
            row = _recap_from_llama(base_url, bodies)
            row["quality"] = quality_report(row["recap"])
            row["in_language"] = in_language(lang, row.get("recap", ""))
            row["latency_ms"] = round((time.time() - t0) * 1000, 1)
            row["model"] = model_name
            row["language"] = lang
            row["script"] = script_of(lang)
            results[lang] = row
        except Exception as exc:
            results[lang] = {
                "model": model_name,
                "language": lang,
                "script": script_of(lang),
                "error": str(exc),
                "latency_ms": round((time.time() - t0) * 1000, 1),
            }
    return results


def score_results(results: dict, fixture: dict) -> list[dict]:
    """Score recorded output with the eval harness scorers."""
    scored = []
    for lang, row in results.items():
        if "error" in row:
            scored.append({
                "language": lang,
                "script": row.get("script", "Latin"),
                "model": row["model"],
                "coverage": None,
                "ungrounded": None,
                "in_language": False,
                "usable": False,
                "latency_ms": row.get("latency_ms", 0),
                "recap": "",
                "error": row["error"],
            })
            continue
        recap = row.get("recap", "")
        expected = fixture.get(lang, {}).get("expected_terms", [])
        evidence = []  # not available without gateway; skip grounding
        cov = scorers.term_coverage(recap, expected)
        in_lang = scorers.in_language(lang, recap)
        usable = row.get("quality", {}).get("usable", False)
        scored.append({
            "language": lang,
            "script": row.get("script", scorers.script_of(lang)),
            "model": row["model"],
            "coverage": {
                "matched": len(cov.matched),
                "expected": len(cov.expected),
                "fraction": round(cov.fraction, 4),
                "missing": cov.missing,
            },
            "ungrounded": None,  # no evidence set without gateway
            "in_language": in_lang,
            "usable": usable,
            "latency_ms": row.get("latency_ms", 0),
            "recap": recap[:200],
        })
    return scored


def build_report(qwen08b: list[dict], qwen2b: list[dict], bonsai: list[dict]) -> str:
    """Build a comparison table."""
    lines = []
    a = lines.append

    a("# Qwen3.5 vs Bonsai-1.7B — Live Benchmark Comparison")
    a("")
    a("> Generated by `demos/multilingual-rollup/benchmark_qwen35.py`")
    a("")

    # Summary stats
    def _stats(rows):
        n = len(rows)
        in_lang = sum(1 for r in rows if r.get("in_language"))
        usable = sum(1 for r in rows if r.get("usable"))
        covs = [r["coverage"]["fraction"] for r in rows if r.get("coverage")]
        avg_cov = sum(covs) / len(covs) if covs else 0
        lats = [r["latency_ms"] for r in rows if r.get("latency_ms", 0) > 0]
        avg_lat = sum(lats) / len(lats) if lats else 0
        return n, in_lang, usable, avg_cov, avg_lat

    s_b = _stats(bonsai)
    s_08 = _stats(qwen08b)
    s_2 = _stats(qwen2b)

    a("## Summary")
    a("")
    a("| Model | Languages | In-language | Usable | Avg coverage | Avg latency (ms) |")
    a("|-------|-----------|-------------|--------|--------------|------------------|")
    a(f"| Bonsai-1.7B Q2_0 (recorded) | {s_b[0]} | {s_b[1]}/{s_b[0]} | {s_b[2]}/{s_b[0]} | {s_b[3]*100:.0f}% | — |")
    if qwen08b:
        a(f"| Qwen3.5-0.8B Q4_K_M (live) | {s_08[0]} | {s_08[1]}/{s_08[0]} | {s_08[2]}/{s_08[0]} | {s_08[3]*100:.0f}% | {s_08[4]:.0f} |")
    if qwen2b:
        a(f"| Qwen3.5-2B Q4_K_M (live)   | {s_2[0]} | {s_2[1]}/{s_2[0]} | {s_2[2]}/{s_2[0]} | {s_2[3]*100:.0f}% | {s_2[4]:.0f} |")
    a("")

    # Per-language comparison
    a("## Per-language results")
    a("")
    a("| Language | Script | Bonsai in-lang | Qwen-0.8B in-lang | Qwen-2B in-lang | Bonsai usable | Qwen-0.8B usable | Qwen-2B usable | Qwen-0.8B latency | Qwen-2B latency |")
    a("|----------|--------|----------------|-------------------|-----------------|---------------|------------------|----------------|-------------------|-----------------|")

    bonsai_by_lang = {r["language"]: r for r in bonsai}
    q08_by_lang = {r["language"]: r for r in qwen08b}
    q2_by_lang = {r["language"]: r for r in qwen2b}

    all_langs = sorted(set(list(bonsai_by_lang.keys()) + list(q08_by_lang.keys()) + list(q2_by_lang.keys())))
    for lang in all_langs:
        b = bonsai_by_lang.get(lang, {})
        q08 = q08_by_lang.get(lang, {})
        q2 = q2_by_lang.get(lang, {})
        script = b.get("script", q08.get("script", q2.get("script", "Latin")))

        def _yn(r, key):
            v = r.get(key)
            if v is None:
                return "—"
            return "yes" if v else "**no**"

        def _lat(r):
            v = r.get("latency_ms")
            if not v:
                return "—"
            return f"{v:.0f}"

        a(f"| {lang} | {script} | {_yn(b, 'in_language')} | {_yn(q08, 'in_language')} | {_yn(q2, 'in_language')} | {_yn(b, 'usable')} | {_yn(q08, 'usable')} | {_yn(q2, 'usable')} | {_lat(q08)} | {_lat(q2)} |")
    a("")

    # Coverage comparison
    a("## Term coverage comparison")
    a("")
    a("| Language | Bonsai coverage | Qwen-0.8B coverage | Qwen-2B coverage |")
    a("|----------|----------------|-------------------|-----------------|")
    for lang in all_langs:
        b = bonsai_by_lang.get(lang, {})
        q08 = q08_by_lang.get(lang, {})
        q2 = q2_by_lang.get(lang, {})

        def _cov(r):
            c = r.get("coverage")
            if not c:
                return "—"
            return f"{c['matched']}/{c['expected']} ({c['fraction']*100:.0f}%)"

        a(f"| {lang} | {_cov(b)} | {_cov(q08)} | {_cov(q2)} |")
    a("")

    # Sample recaps
    a("## Sample recaps (first 200 chars)")
    a("")
    for lang in all_langs[:5]:
        a(f"### {lang}")
        a("")
        b = bonsai_by_lang.get(lang, {})
        q08 = q08_by_lang.get(lang, {})
        q2 = q2_by_lang.get(lang, {})
        a(f"**Bonsai-1.7B**: {b.get('recap', '—')}")
        a("")
        a(f"**Qwen3.5-0.8B**: {q08.get('recap', '—')}")
        a("")
        a(f"**Qwen3.5-2B**: {q2.get('recap', '—')}")
        a("")

    return "\n".join(lines)


def main():
    dataset = json.loads(DATASET.read_text(encoding="utf-8"))
    fixture_path = REPO / "demos" / "synthesis-eval" / "fixtures" / "expected_terms.json"
    fixture = json.loads(fixture_path.read_text(encoding="utf-8"))["multilingual"]

    # Get the recorded Bonsai baseline
    bonsai_results_path = RESULTS_DIR / "rollup_results.json"
    if not bonsai_results_path.exists():
        print("ERROR: No recorded Bonsai baseline found at", bonsai_results_path, file=sys.stderr)
        return 1
    bonsai_raw = json.loads(bonsai_results_path.read_text(encoding="utf-8"))
    bonsai_matrix = bonsai_raw.get("multilingual_matrix", {})

    # Score the Bonsai baseline
    bonsai_scored = []
    for lang, row in bonsai_matrix.items():
        recap = row.get("recap", "")
        expected = fixture.get(lang, {}).get("expected_terms", [])
        cov = scorers.term_coverage(recap, expected)
        bonsai_scored.append({
            "language": lang,
            "script": row.get("script", scorers.script_of(lang)),
            "model": "Bonsai-1.7B Q2_0",
            "coverage": {
                "matched": len(cov.matched),
                "expected": len(cov.expected),
                "fraction": round(cov.fraction, 4),
                "missing": cov.missing,
            },
            "in_language": scorers.in_language(lang, recap),
            "usable": row.get("quality", {}).get("usable", False),
            "latency_ms": 0,
            "recap": recap[:200],
        })

    # Benchmark Qwen3.5-0.8B
    qwen08b_scored = []
    print(f"Benchmarking Qwen3.5-0.8B at {LLAMA_08B}...")
    try:
        # Health check
        urllib.request.urlopen(LLAMA_08B + "/health", timeout=10).read()
        qwen08b_raw = benchmark_model(LLAMA_08B, dataset, "Qwen3.5-0.8B Q4_K_M")
        qwen08b_scored = score_results(qwen08b_raw, fixture)
        print(f"  Done: {len(qwen08b_scored)} languages")
    except Exception as e:
        print(f"  SKIP: {e}")

    # Benchmark Qwen3.5-2B
    qwen2b_scored = []
    print(f"Benchmarking Qwen3.5-2B at {LLAMA_2B}...")
    try:
        urllib.request.urlopen(LLAMA_2B + "/health", timeout=10).read()
        qwen2b_raw = benchmark_model(LLAMA_2B, dataset, "Qwen3.5-2B Q4_K_M")
        qwen2b_scored = score_results(qwen2b_raw, fixture)
        print(f"  Done: {len(qwen2b_scored)} languages")
    except Exception as e:
        print(f"  SKIP: {e}")

    # Build report
    report = build_report(qwen08b_scored, qwen2b_scored, bonsai_scored)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "qwen35_benchmark.md").write_text(report, encoding="utf-8")

    # Save JSON
    output = {
        "bonsai_1p7b_recorded": bonsai_scored,
        "qwen35_0p8b_live": qwen08b_scored,
        "qwen35_2b_live": qwen2b_scored,
    }
    (RESULTS_DIR / "qwen35_benchmark.json").write_text(
        json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"\nWrote {RESULTS_DIR / 'qwen35_benchmark.md'}")
    print(f"Wrote {RESULTS_DIR / 'qwen35_benchmark.json'}")

    # Print summary to stdout
    print("\n" + "=" * 80)
    print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())

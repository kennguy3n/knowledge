//! Graph-of-Thought (GoT) reasoning over the concept graph.
//!
//! Per `PROPOSAL.md` §11.1 ("multi-step reasoning") and `PHASES.md`
//! Phase 6, the substrate's reasoning plane explores a directed
//! graph of *thoughts* — hypotheses, evidence, conclusions,
//! questions, refinements — connected by typed edges (`Supports`,
//! `Contradicts`, `Refines`, `Derives`, `Aggregates`).
//!
//! The executor is intentionally synchronous and budget-bounded so
//! it can be unit-tested against deterministic fakes; the production
//! runtime wires expansion to an SLM call (or to graph traversal
//! when factual grounding is needed) behind the same trait.
//!
//! # Pipeline
//!
//! 1. [`GoTExecutor::plan`] — turn a [`GoTQuery`] into a
//!    [`GoTPlan`] (initial decomposition into a question root
//!    plus zero or more sub-questions).
//! 2. [`GoTExecutor::expand`] — generate child thoughts from a
//!    leaf via a pluggable [`Expander`].
//! 3. [`GoTExecutor::evaluate`] — score every root → leaf path,
//!    return the best [`GoTResult`].
//! 4. [`GoTExecutor::execute`] — full pipeline; the result is
//!    serialisable for the reasoning plane and may be persisted as
//!    a [`crate::workflow::WorkflowTrace`].

use std::collections::{HashMap, VecDeque};

use chrono::{DateTime, Utc};
use concept_graph::{ConceptGraph, NodeId, RelationType};
use evidence_store::ScopeId;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::planner::{QueryClass, RetrievalMode};

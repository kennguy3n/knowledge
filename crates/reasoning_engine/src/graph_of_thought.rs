    fn scope() -> ScopeId {
        ScopeId::new_v4()
    }

    fn evidence(content: &str, conf: f64, parent: ThoughtId, s: ScopeId) -> ThoughtNode {
        ThoughtNode::new(content, ThoughtType::Evidence, conf, s).with_parents(vec![parent])
    }

    fn conclusion(content: &str, conf: f64, parent: ThoughtId, s: ScopeId) -> ThoughtNode {
        ThoughtNode::new(content, ThoughtType::Conclusion, conf, s).with_parents(vec![parent])
    }

    fn run(
        exec: &GoTExecutor,
        graph: &mut ThoughtGraph,
        plan: &GoTPlan,
        query: &GoTQuery,
        expander: &StaticExpander,
    ) -> GoTResult {
        let exhausted = exec.expand_all(graph, plan, query, expander);
        let mut result = exec.evaluate(graph).expect("evaluate");
        result.budget_exhausted = exhausted;
        result
    }

    #[test]
    fn single_hop_reasoning_runs_to_completion() {
        let s = scope();
        let q = GoTQuery::new("Why did Atlas slip?", s).with_budget(2, 2, 16);
        let mut graph = ThoughtGraph::new();
        let exec = GoTExecutor::new();
        let plan = exec.plan(&mut graph, &q);
        let mut expander = StaticExpander::new();
        expander.register(
            plan.root,
            vec![(
                conclusion(
                    "Spec slipped because of dependency on KMS",
                    0.9,
                    plan.root,
                    s,
                ),
                ThoughtEdge::Derives,
            )],
        );
        let result = run(&exec, &mut graph, &plan, &q, &expander);
        assert!(!result.best_path.is_empty());
        assert!(result.confidence > 0.0);
        assert!(matches!(
            result.best_path.last().unwrap().thought_type,
            ThoughtType::Conclusion
        ));
    }

    #[test]
    fn multi_branch_explores_and_picks_best() {
        let s = scope();
        let q = GoTQuery::new("Why does the bench run hot?", s)
            .with_budget(3, 3, 32)
            .with_strategy(GoTStrategy::BestFirst);
        let mut graph = ThoughtGraph::new();
        let exec = GoTExecutor::new();
        let plan = exec.plan(&mut graph, &q);
        let mut expander = StaticExpander::new();
        let h1 = ThoughtNode::new("Disk thrash", ThoughtType::Hypothesis, 0.4, s)
            .with_parents(vec![plan.root]);
        let h2 = ThoughtNode::new("CPU pinned", ThoughtType::Hypothesis, 0.85, s)
            .with_parents(vec![plan.root]);
        let h1_id = h1.id;
        let h2_id = h2.id;
        expander.register(
            plan.root,
            vec![(h1, ThoughtEdge::Supports), (h2, ThoughtEdge::Supports)],
        );
        expander.register(
            h1_id,
            vec![(
                evidence("iostat shows idle", 0.3, h1_id, s),
                ThoughtEdge::Contradicts,
            )],
        );
        expander.register(
            h2_id,
            vec![(
                conclusion("Pin to fewer cores", 0.95, h2_id, s),
                ThoughtEdge::Derives,
            )],
        );
        let result = run(&exec, &mut graph, &plan, &q, &expander);
        // Best path should run through the high-confidence hypothesis.
        assert!(result
            .best_path
            .iter()
            .any(|t| t.content.contains("CPU pinned")));
        assert!(result
            .best_path
            .iter()
            .any(|t| matches!(t.thought_type, ThoughtType::Conclusion)));
        assert!(graph.len() >= 4, "graph should contain at least 4 thoughts");
    }

    #[test]
    fn max_depth_caps_expansion() {
        let s = scope();
        let q = GoTQuery::new("chain", s).with_budget(2, 1, 100);
        let mut graph = ThoughtGraph::new();
        let exec = GoTExecutor::new();
        let plan = exec.plan(&mut graph, &q);
        // Build a 5-deep chain via the expander; only depth 2 should
        // be reached from root.
        let mut expander = StaticExpander::new();
        let mut prev = plan.root;
        let mut step_ids = Vec::new();
        for i in 0..5 {
            let n = ThoughtNode::new(format!("step-{i}"), ThoughtType::Hypothesis, 0.8, s)
                .with_parents(vec![prev]);
            let id = n.id;
            expander.register(prev, vec![(n, ThoughtEdge::Derives)]);
            step_ids.push(id);
            prev = id;
        }
        let _result = run(&exec, &mut graph, &plan, &q, &expander);
        // Root + 2 expansions = at most 3 thoughts in the chain.
        assert!(graph.len() <= 3);
    }

